// REFRESH THE DISPOSABLE-MAILBOX LIST (2026-10-02) — src/lib/disposableDomains.ts.
//
//   node scripts/maintenance/update-disposable-domains.mjs
//
// The source is the community list at
// github.com/disposable-email-domains/disposable-email-domains
// (disposable_email_blocklist.conf, CC0, updated most days; entries are added
// only for services that hand out throwaway inboxes, and a domain wrongly
// listed is moved to its allowlist). The file is rewritten in full — one
// domain a line, sorted, the fetch date in its header — so the diff of a
// refresh is the list's own change. Our own additions and exceptions are not
// in that file: they live in src/lib/disposableEmail.ts.
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const BASE = "https://raw.githubusercontent.com/disposable-email-domains/disposable-email-domains/main";
const OUT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..", "..", "src", "lib", "disposableDomains.ts");

async function lines(file) {
  const res = await fetch(`${BASE}/${file}`, { signal: AbortSignal.timeout(30_000) });
  if (!res.ok) throw new Error(`${file}: HTTP ${res.status}`);
  return (await res.text())
    .split(/\r?\n/)
    .map((l) => l.trim().toLowerCase())
    .filter((l) => l && !l.startsWith("#"));
}

const block = await lines("disposable_email_blocklist.conf");
const allow = new Set(await lines("allowlist.conf").catch(() => []));
const domains = [...new Set(block)].filter((d) => /^[a-z0-9.-]+\.[a-z0-9-]+$/.test(d) && !allow.has(d)).sort();
if (domains.length < 1000) throw new Error(`only ${domains.length} domains came back — not overwriting the list`);

const day = new Date().toISOString().slice(0, 10);
writeFileSync(
  OUT,
  `// GENERATED by scripts/maintenance/update-disposable-domains.mjs — do not edit by hand.
// Source: https://github.com/disposable-email-domains/disposable-email-domains
//         disposable_email_blocklist.conf minus allowlist.conf (CC0-1.0)
// Fetched: ${day} · ${domains.length} domains
// Read through lib/disposableEmail, which adds our own entries and exceptions.
import "server-only";

export const DISPOSABLE_DOMAINS_FETCHED = "${day}";

export const DISPOSABLE_DOMAINS = \`
${domains.join("\n")}
\`;
`,
);
console.log(`wrote ${domains.length} domains (${day}) to ${path.relative(process.cwd(), OUT)}`);
