export const AI_SPECIALTY_GROUPS: AiSpecialtyGroup[] = GROUP_DEFS.map((group) => ({
  ...group,
  specialtyIds: SPECIALTY_DEFINITIONS.filter((spec) => spec.groups.includes(group.id)).map((spec) => spec.id),
}));

// Synchronous version for backwards compatibility
export function getAiSpecialtiesSync(): AiSpecialty[] {
  return AI_SPECIALTIES;
}

export function getAiSpecialtyGroups(): AiSpecialtyGroup[] {
  return AI_SPECIALTY_GROUPS;
}

export function getAiSpecialtyByIdSync(id: string): AiSpecialty | undefined {
  return AI_SPECIALTIES.find((specialty) => specialty.id === id);
}


