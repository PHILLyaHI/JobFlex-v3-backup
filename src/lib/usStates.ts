export type USStateCode = (typeof US_STATES)[number]["code"];

/** Splits a "City, ST" string into its parts. Anything after the last comma is treated as the state. */
export function parseCityState(location: string): { city: string; state: string } {
  const trimmed = location.trim();
  const lastComma = trimmed.lastIndexOf(",");
  if (lastComma === -1) return { city: trimmed, state: "" };
  const city = trimmed.slice(0, lastComma).trim();
  const statePart = trimmed.slice(lastComma + 1).trim().toUpperCase();
  const state = US_STATES.some((s) => s.code === statePart) ? statePart : "";
  return state ? { city, state } : { city: trimmed, state: "" };
}

export function formatCityState(city: string, state: string): string {
  const trimmedCity = city.trim();
  if (!state) return trimmedCity;
  return trimmedCity ? `${trimmedCity}, ${state}` : state;
}
